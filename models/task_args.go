// IsNil checks if an interface{} value is nil
func IsNil(v interface{}) bool {
	if v == nil {
		return true
	}
	rv := reflect.ValueOf(v)
	switch rv.Kind() {
	case reflect.Ptr, reflect.Map, reflect.Slice, reflect.Interface, reflect.Chan, reflect.Func:
		return rv.IsNil()
	default:
		return false
	}
}

func ValidateTaskArgsJsonStr(jsonStr string, taskType ChainTaskType) (validationError, err error) {
	switch taskType {
	case TaskTypeSD:
		return validateTaskArgsAgainstSchema(jsonStr, &sdInferenceTaskSchema, func() string {
			return config.GetConfig().TaskSchema.StableDiffusionInference
		})
	case TaskTypeLLM:
		return validateTaskArgsAgainstSchema(jsonStr, &gptInferenceTaskSchema, func() string {
			return config.GetConfig().TaskSchema.GPTInference
		})
	case TaskTypeSDFTLora:
		return validateTaskArgsAgainstSchema(jsonStr, &sdFinetuneLoraTaskSchema, func() string {
			return config.GetConfig().TaskSchema.StableDiffusionFinetuneLora
		})
	case TaskTypeVideo:
		return validateTaskArgsAgainstSchema(jsonStr, &videoInferenceTaskSchema, func() string {
			return config.GetConfig().TaskSchema.VideoInference
		})
	default:
		return nil, fmt.Errorf("unsupported task type %d", taskType)
	}
}

func validateTaskArgsAgainstSchema(
	jsonStr string,
	cached **jsonschema.Schema,
	schemaURL func() string,
) (validationError, err error) {
	taskArgsSchemaMu.Lock()
	defer taskArgsSchemaMu.Unlock()
	if *cached == nil {
		schemaJson := schemaURL()
		if !isValidUrl(schemaJson) {
			return nil, errors.New("invalid URL for task json schema")
		}
		compiled, compileErr := jsonschema.Compile(schemaJson)
		if compileErr != nil {
			return nil, compileErr
		}
		*cached = compiled
	}

	var v interface{}
	if err := json.Unmarshal([]byte(jsonStr), &v); err != nil {
		return nil, err
	}
	return (*cached).Validate(v), nil
}

// sdTaskArgsModels holds the model related fields of image TaskArgs 3.7.0.
type sdTaskArgsModels struct {
	BaseModel struct {
		Name string `json:"name"`
	} `json:"base_model"`
	TaskConfig struct {
		NumImagesPerPrompt *int `json:"num_images_per_prompt"`
	} `json:"task_config"`
	Lora *struct {
		Model string `json:"model"`
	} `json:"lora"`
	Components map[string]struct {
		Repo string `json:"repo"`
	} `json:"components"`
}

func parseSDTaskArgsModels(taskArgs string) (*sdTaskArgsModels, error) {
	var args sdTaskArgsModels
	if err := json.Unmarshal([]byte(taskArgs), &args); err != nil {
		return nil, err
	}
	return &args, nil
}

func (args *sdTaskArgsModels) baseModelName() (string, error) {
	if args.BaseModel.Name == "" {
		return "", errors.New("base_model.name is missing or empty")
	}
	return args.BaseModel.Name, nil
}

// GetTaskConfigNumImages returns the number of images generated by an image task.
// A missing num_images_per_prompt takes the TaskArgs default of 1.
func GetTaskConfigNumImages(taskArgs string) (int, error) {
	args, err := parseSDTaskArgsModels(taskArgs)
	if err != nil {
		return 0, err
	}
	if args.TaskConfig.NumImagesPerPrompt == nil {
		return 1, nil
	}
	return *args.TaskConfig.NumImagesPerPrompt, nil
}

func GetSDTaskConfigBaseModel(taskArgs string) (string, error) {
	args, err := parseSDTaskArgsModels(taskArgs)
	if err != nil {
		return "", err
	}
	return args.baseModelName()
}

func getSDTaskConfigModelIDs(taskArgs string) ([]string, error) {
	args, err := parseSDTaskArgsModels(taskArgs)
	if err != nil {
		return nil, err
	}
	baseModel, err := args.baseModelName()
	if err != nil {
		return nil, err
	}
	modelIDs := []string{"base:" + baseModel}
	if args.Lora != nil {
		if args.Lora.Model == "" {
			return nil, errors.New("lora.model is missing or empty")
		}
		modelIDs = append(modelIDs, "lora:"+args.Lora.Model)
	}
	names := make([]string, 0, len(args.Components))
	for name := range args.Components {
		names = append(names, name)
	}
	slices.Sort(names)
	for _, name := range names {
		repo := args.Components[name].Repo
		if repo == "" {
			return nil, fmt.Errorf("components.%s.repo is missing or empty", name)
		}
		modelIDs = append(modelIDs, "component:"+name+":"+repo)
	}
	return modelIDs, nil
}

func getGPTTaskConfigModelIDs(taskArgs string) ([]string, error) {
	var taskArgsMap map[string]interface{}

	err := json.Unmarshal([]byte(taskArgs), &taskArgsMap)
	if err != nil {
		return nil, err
	}

	modelValue, ok := taskArgsMap["model"]
	if !ok || IsNil(modelValue) {
		return nil, errors.New("model is missing or null")
	}
	model, ok := modelValue.(string)
	if !ok {
		return nil, errors.New("model is not a string")
	}
	modelIDs := []string{"base:" + model}
	return modelIDs, nil
}

func getSDFTTaskConfigModelIDs(taskArgs string) ([]string, error) {
	var taskArgsMap map[string]interface{}

	err := json.Unmarshal([]byte(taskArgs), &taskArgsMap)
	if err != nil {
		return nil, err
	}

	modelValue, ok := taskArgsMap["model"]
	if !ok || IsNil(modelValue) {
		return nil, errors.New("model is missing or null")
	}

	var baseModel string
	model, ok := modelValue.(map[string]interface{})
	if !ok {
		return nil, errors.New("model is not an object")
	}

	nameValue, ok := model["name"]
	if !ok || IsNil(nameValue) {
		return nil, errors.New("model.name is missing or null")
	}
	name, ok := nameValue.(string)
	if !ok {
		return nil, errors.New("model.name is not a string")
	}
	baseModel = name
	if originVariant, ok := model["variant"]; ok && !IsNil(originVariant) {
		variant, ok1 := originVariant.(string)
		if ok1 {
			baseModel = baseModel + "+" + variant
		}
	}
	modelIDs := []string{"base:" + baseModel}
	return modelIDs, nil
}

func getVideoTaskConfigModelIDs(taskArgs string) ([]string, error) {
	var args struct {
		BaseModel struct {
			Name string `json:"name"`
		} `json:"base_model"`
		Loras []struct {
			Model          string  `json:"model"`
			Revision       *string `json:"revision"`
			WeightFileName string  `json:"weight_file_name"`
		} `json:"loras"`
		Components map[string]struct {
			Repo string `json:"repo"`
		} `json:"components"`
	}
	if err := json.Unmarshal([]byte(taskArgs), &args); err != nil {
		return nil, err
	}
	if args.BaseModel.Name == "" {
		return nil, errors.New("base_model.name is missing or empty")
	}
	ids := []string{"base:" + args.BaseModel.Name}
	for i, lora := range args.Loras {
		if lora.Model == "" {
			return nil, fmt.Errorf("loras[%d].model is missing or empty", i)
		}
		loraID := "lora:" + lora.Model
		if !strings.HasPrefix(lora.Model, "http://") && !strings.HasPrefix(lora.Model, "https://") {
			if lora.Revision != nil && *lora.Revision != "" {
				loraID += "@" + NormalizeCommitRevision(*lora.Revision)
			}
			if lora.WeightFileName != "" {
				loraID += "#" + lora.WeightFileName
			}
		}
		ids = append(ids, loraID)
	}
	names := make([]string, 0, len(args.Components))
	for name := range args.Components {
		names = append(names, name)
	}
	slices.Sort(names)
	for _, name := range names {
		repo := args.Components[name].Repo
		if repo == "" {
			return nil, fmt.Errorf("components.%s.repo is missing or empty", name)
		}
		ids = append(ids, "component:"+name+":"+repo)
	}
	return NormalizeModelIDs(ids), nil
}

